-- Modelo didáctico para una base Firebird incrustada NUEVA en LibreOffice Base.
-- En Herramientas > SQL, ejecutar cada sentencia de forma individual.
-- No contiene DROP ni datos personales. No volver a insertar sobre la misma base.
CREATE TABLE AULA (
    ID_AULA INTEGER NOT NULL PRIMARY KEY,
    NOMBRE VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE EQUIPO (
    ID_EQUIPO INTEGER NOT NULL PRIMARY KEY,
    CODIGO VARCHAR(20) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR(100) NOT NULL,
    ID_AULA INTEGER NOT NULL,
    CONSTRAINT FK_EQUIPO_AULA FOREIGN KEY (ID_AULA) REFERENCES AULA(ID_AULA)
);

CREATE TABLE INCIDENCIA (
    ID_INCIDENCIA INTEGER NOT NULL PRIMARY KEY,
    ID_EQUIPO INTEGER NOT NULL,
    FECHA_ALTA DATE NOT NULL,
    FECHA_CIERRE DATE,
    RESUMEN VARCHAR(150) NOT NULL,
    ESTADO VARCHAR(15) NOT NULL,
    CONSTRAINT FK_INCIDENCIA_EQUIPO FOREIGN KEY (ID_EQUIPO) REFERENCES EQUIPO(ID_EQUIPO),
    CONSTRAINT CK_ESTADO CHECK (ESTADO IN ('Abierta', 'En curso', 'Cerrada')),
    CONSTRAINT CK_FECHAS CHECK (FECHA_CIERRE IS NULL OR FECHA_CIERRE >= FECHA_ALTA),
    CONSTRAINT CK_CIERRE CHECK (
        (ESTADO = 'Cerrada' AND FECHA_CIERRE IS NOT NULL)
        OR (ESTADO IN ('Abierta', 'En curso') AND FECHA_CIERRE IS NULL)
    )
);

