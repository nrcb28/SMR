-- Ejecutar cada SELECT como consulta independiente.
-- Incidencias sin fecha de cierre: dos filas en el conjunto inicial.
SELECT I.ID_INCIDENCIA, E.CODIGO, A.NOMBRE AS AULA,
       I.FECHA_ALTA, I.RESUMEN, I.ESTADO
FROM INCIDENCIA I
JOIN EQUIPO E ON E.ID_EQUIPO = I.ID_EQUIPO
JOIN AULA A ON A.ID_AULA = E.ID_AULA
WHERE I.FECHA_CIERRE IS NULL
ORDER BY I.FECHA_ALTA, I.ID_INCIDENCIA;

-- Todos los equipos, incluso los que no tienen incidencias.
-- Recuentos iniciales: PC-001=2, PC-002=1, PC-003=0, PC-004=0.
SELECT E.CODIGO, COUNT(I.ID_INCIDENCIA) AS TOTAL_INCIDENCIAS
FROM EQUIPO E
LEFT JOIN INCIDENCIA I ON I.ID_EQUIPO = E.ID_EQUIPO
GROUP BY E.CODIGO
ORDER BY E.CODIGO;

-- Número de equipos por aula: 2, 1 y 1 en los datos iniciales.
SELECT A.NOMBRE, COUNT(E.ID_EQUIPO) AS TOTAL_EQUIPOS
FROM AULA A
LEFT JOIN EQUIPO E ON E.ID_AULA = A.ID_AULA
GROUP BY A.NOMBRE
ORDER BY A.NOMBRE;
