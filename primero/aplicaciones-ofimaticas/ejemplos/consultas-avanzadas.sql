-- Consultas de lectura para el esquema taller.sql. Ejecutar de una en una.
-- Resultados esperados con el conjunto inicial, no con una base ya ampliada.

-- 1. Abiertas por equipo: PC-001=1, PC-002=1, PC-003=0, PC-004=0.
SELECT E.CODIGO, COUNT(I.ID_INCIDENCIA) AS ABIERTAS
FROM EQUIPO E
LEFT JOIN INCIDENCIA I
  ON I.ID_EQUIPO = E.ID_EQUIPO AND I.FECHA_CIERRE IS NULL
GROUP BY E.CODIGO
ORDER BY E.CODIGO;

-- 2. Sin incidencias: PC-003 y PC-004.
SELECT E.CODIGO
FROM EQUIPO E
WHERE NOT EXISTS (
  SELECT 1 FROM INCIDENCIA I WHERE I.ID_EQUIPO = E.ID_EQUIPO
)
ORDER BY E.CODIGO;

-- 3. Dos o más incidencias históricas: PC-001, total 2.
SELECT E.CODIGO, COUNT(I.ID_INCIDENCIA) AS TOTAL
FROM EQUIPO E
JOIN INCIDENCIA I ON I.ID_EQUIPO = E.ID_EQUIPO
GROUP BY E.CODIGO
HAVING COUNT(I.ID_INCIDENCIA) >= 2
ORDER BY E.CODIGO;

-- 4. Aula y equipos, conservando aulas vacías: 2,1,1 inicialmente.
SELECT A.NOMBRE, COUNT(E.ID_EQUIPO) AS EQUIPOS
FROM AULA A
LEFT JOIN EQUIPO E ON E.ID_AULA = A.ID_AULA
GROUP BY A.ID_AULA, A.NOMBRE
ORDER BY A.NOMBRE;

-- 5. Incidencias de noviembre de 2026: IDs 1 y 3.
SELECT ID_INCIDENCIA, FECHA_ALTA, RESUMEN
FROM INCIDENCIA
WHERE FECHA_ALTA >= DATE '2026-11-01'
  AND FECHA_ALTA < DATE '2026-12-01'
ORDER BY FECHA_ALTA, ID_INCIDENCIA;

-- 6. Conteo por estado: Abierta=1, Cerrada=1, En curso=1.
SELECT ESTADO, COUNT(*) AS TOTAL
FROM INCIDENCIA
GROUP BY ESTADO
ORDER BY ESTADO;
